        "| probe | pooling | layer | threshold | val AUROC | val F1 | val FPR at TPR | test AUROC | test F1 | test FPR at TPR |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
